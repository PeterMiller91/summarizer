@dataclass
class SummarizeOptions:
    style: str
    length: str
    audience: str
    language: str
    focus: str
    chapters: bool
    quotes: bool
    action_items: bool


def extract_video_id(url: str) -> Optional[str]:
    if not url:
        return None
    m = YOUTUBE_REGEX.search(url.strip())
    return m.group(1) if m else None


@st.cache_data(show_spinner=False)
def fetch_transcript(video_id: str, preferred_langs: Tuple[str, ...]) -> str:
    """
    Fetches transcript text if available.
    Tries preferred languages in order.
    """
    transcripts = YouTubeTranscriptApi.list_transcripts(video_id)

    # Try manual transcripts first, then autogenerated, per language preference
    for lang in preferred_langs:
        try:
            t = transcripts.find_manually_created_transcript([lang])
            parts = t.fetch()
            return "\n".join(p["text"] for p in parts)
        except Exception:
            pass

        try:
            t = transcripts.find_generated_transcript([lang])
            parts = t.fetch()
            return "\n".join(p["text"] for p in parts)
        except Exception:
            pass

    # If nothing worked, raise for outer handling
    raise NoTranscriptFound(video_id)


def clean_transcript(text: str) -> str:
    # Remove artifacts like [Music], excessive whitespace, etc.
    text = re.sub(r"\[.*?\]", "", text)
    text = re.sub(r"\s+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def chunk_text_by_words(text: str, max_words: int = 1800) -> List[str]:
    words = text.split()
    if len(words) <= max_words:
        return [text]
    chunks = []
    start = 0
    while start < len(words):
        end = min(start + max_words, len(words))
        chunk = " ".join(words[start:end])
        chunks.append(chunk)
        start = end
    return chunks


def build_system_prompt(opts: SummarizeOptions) -> str:
    return (
        "Du bist ein sehr präziser Redakteur und Analyst für Video-Inhalte. "
        "Du fasst Inhalte strukturiert zusammen, ohne zu halluzinieren. "
        "Wenn etwas im Transkript nicht eindeutig belegt ist, markiere es als Unsicherheit."
    )


def build_user_prompt(transcript: str, opts: SummarizeOptions) -> str:
    extras = []
    if opts.chapters:
        extras.append("Erstelle sinnvolle Kapitelüberschriften (mit kurzen Beschreibungen).")
    if opts.quotes:
        extras.append("Extrahiere 3–7 starke Zitate (kurz, prägnant).")
    if opts.action_items:
        extras.append("Leite konkrete Action Items / nächste Schritte ab.")

    extras_txt = "\n- " + "\n- ".join(extras) if extras else ""

    return f"""
Kontext: Du bekommst das Transkript eines YouTube-Videos.

Anforderungen:
- Stil: {opts.style}
- Länge: {opts.length}
- Zielgruppe: {opts.audience}
- Sprache der Ausgabe: {opts.language}
- Fokus: {opts.focus}

Zusätzliche Elemente:{extras_txt if extras_txt else "\n- Keine"}

Output-Format (immer in Markdown):
1) Titel (falls aus Inhalt ableitbar, sonst neutral)
2) Kurzüberblick (2–4 Sätze)
3) Hauptpunkte (je nach Länge)
4) Details / Beispiele (wenn Länge = lang oder Stil das verlangt)
5) (Optional) Kapitel
6) (Optional) Zitate
7) (Optional) Action Items

Transkript:
\"\"\"
{transcript}
\"\"\"
""".strip()


def call_llm(prompt: str, system: str, model: str = DEFAULT_MODEL, max_output_tokens: int = 900) -> str:
    if not client:
        raise RuntimeError("OPENAI_API_KEY fehlt. Bitte als ENV setzen oder in Streamlit Secrets hinterlegen.")

    resp = client.responses.create(
        model=model,
        input=[
            {"role": "system", "content": system},
            {"role": "user", "content": prompt},
        ],
        max_output_tokens=max_output_tokens,
    )
    return resp.output_text


def summarize_transcript(transcript: str, opts: SummarizeOptions) -> str:
    transcript = clean_transcript(transcript)
    chunks = chunk_text_by_words(transcript, max_words=1800)

    system = build_system_prompt(opts)

    # Output length heuristics
    length_to_tokens = {
        "kurz (5 bullets)": 450,
        "mittel": 900,
        "lang (mit Beispielen)": 1400,
    }
    max_out = length_to_tokens.get(opts.length, 900)

    if len(chunks) == 1:
        user_prompt = build_user_prompt(chunks[0], opts)
        return call_llm(user_prompt, system, max_output_tokens=max_out)

    # Map: summarize each chunk
    partials = []
    for i, ch in enumerate(chunks, start=1):
        chunk_prompt = build_user_prompt(ch, opts) + f"\n\nHinweis: Das ist Teil {i}/{len(chunks)}. Erzeuge eine Teilzusammenfassung."
        partials.append(call_llm(chunk_prompt, system, max_output_tokens=650))

    # Reduce: summarize summaries
    merged = "\n\n---\n\n".join(partials)
    reduce_prompt = f"""
Du bekommst mehrere Teilzusammenfassungen eines langen Videos.
Erzeuge daraus eine konsistente, nicht redundante Gesamtsummary nach diesen Einstellungen:
- Stil: {opts.style}
- Länge: {opts.length}
- Zielgruppe: {opts.audience}
- Sprache: {opts.language}
- Fokus: {opts.focus}

Teilzusammenfassungen:
\"\"\"
{merged}
\"\"\"
""".strip()

    return call_llm(reduce_prompt, system, max_output_tokens=max_out)


